const DICTS: Record<Lang, Dict> = { en, es, fr, hi, zh };

const I18nContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({
  lang: "en",
  setLang: () => {},
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = localStorage.getItem("finsight-lang");
    if (saved === "en" || saved === "es" || saved === "fr" || saved === "hi" || saved === "zh") {
      setLangState(saved);
      document.documentElement.lang = saved === "zh" ? "zh-Hans" : saved;
    }
  }, []);

  function setLang(next: Lang) {
    setLangState(next);
    localStorage.setItem("finsight-lang", next);
    document.documentElement.lang = next === "zh" ? "zh-Hans" : next;
  }

  return <I18nContext.Provider value={{ lang, setLang }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const { lang, setLang } = useContext(I18nContext);
  function t(key: keyof Dict, vars?: Record<string, string | number>) {
    const raw = DICTS[lang][key] ?? en[key];
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
  }
  function cat(name: string) {
    const key = `cat_${name}` as keyof Dict;
    return key in en ? t(key) : name;
  }
  return { lang, setLang, t, cat };
}

export function LanguageSwitch() {
  const { lang, setLang } = useI18n();
  return (
    <div className="langs" role="group" aria-label="Language">
      {LANGS.map((item) => (
        <button
          key={item.id}
          type="button"
          className={item.id === lang ? "on" : ""}
          onClick={() => setLang(item.id)}
          aria-pressed={item.id === lang}
        >
          {item.short}
        </button>
      ))}
    </div>
  );
}
